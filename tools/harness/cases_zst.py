def fallback(num, log):
    """(shown, observed) of entry num's static fallback, or None when it has none"""
    r = FALLBACK.get(num)
    return static_check(r[2], r[3], r[4], r[5], log) if r else None


def source_line(path, frag):
    for k, line in enumerate(open(mom.ROOT + path, encoding='latin-1'), 1):
        if frag in line:
            return k
    return None


def static_check(prog, funcs, path, frag, log):
    exe = EXE_DIR + prog + '.EXE'
    ln = source_line(path, frag)
    parts, ok = [], ln is not None
    parts.append('%s:%s holds the code' % (path[4:], ln) if ln else '%s: code NOT FOUND' % path[4:])
    for f in funcs:
        fo, n, a = exefn.locate(prog, f)
        same, diff = exefn.same_as_131(prog, f, exe)
        log.append('  %s %s (%s) file 0x%x, %d bytes: %s' % (prog, f, a, fo, n, 'same' if same else
                                                              'differs at %s' % ['%x' % d for d in diff[:12]]))
        parts.append('%s %s' % (f, '= 1.31 bytes' if same else 'CHANGED (%d bytes differ)' % len(diff)))
        ok = ok and same
    return ok, '; '.join(parts) + ' [%s]' % exe.replace(mom.ROOT, '')


def _make(num, title, prog, funcs, path, frag):
    @case(num, 'ST', title, setup='static: source line + function bytes of %s.EXE' % prog,
          bug='the 1.31 code is there (function bytes = 1.31)', fixed='the function changed')
    def run(log):
        shown, obs = static_check(prog, funcs, path, frag, log)
        return dict(shown=shown, observed=obs)
    return run


