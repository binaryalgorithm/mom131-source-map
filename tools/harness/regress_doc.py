"""Brings the regression results into the documents (P4 B4):
  - tools/harness/TEST_CASES.txt: the section between the REGRESSION markers is rebuilt from the registered cases
    (tools/harness/cases_*.py) and their latest result (work/harness/regress/results.tsv);
  - BUGS_AND_QUIRKS.txt: an entry whose case showed the bug gets status GAME and one line 'In game (DATE,
    regress.py #N): observed'; a case that did not show it gets the line only ('not shown in game ...').
  python -P tools/harness/regress_doc.py            (dry run: what would change)
  python -P tools/harness/regress_doc.py --write"""
import os
import re
import sys
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import regress as R                            # noqa: E402

ROOT = R.mom.ROOT
TC = HERE + '/TEST_CASES.txt'
BQ = ROOT + 'BUGS_AND_QUIRKS.txt'
B0, B1 = '=== REGRESSION SUITE (tools/harness/regress.py; generated by regress_doc.py) ===', '=== END REGRESSION SUITE ==='

R.load_cases()
latest = {}
if os.path.exists(R.OUT + 'results.tsv'):
    for l in open(R.OUT + 'results.tsv', encoding='utf-8'):
        p = l.rstrip('\n').split('\t')
        # local paths in quoted tracebacks -> repository-relative (the documents are published)
        p[4] = re.sub(r'(?:[A-Za-z]:)?[^\s"|]*?masterofmagic131[\\/]', '', p[4])
        if p[3] == 'NOT SHOWN' and re.search(r'not reached|not called|did not reach|was not written|no write by|'
                                             r'no Diplo|no Spell_Casting_Cost|no AI-AI|not found after|not in the '
                                             r'battle|unstable reads', p[4]):
            p[3] = 'NOT REACHED'                # runs from before the NOT REACHED verdict (10/23)
        latest[int(p[0])] = p                   # the last run of each case wins

blocks = [B0, 'Run: python -P tools/harness/regress.py NUM ... | --kind KIND; results work/harness/regress/. A case shows '
              '1.31\'s behaviour (BUG SHOWN) or not; a fixed build should give NOT SHOWN.']
for n in sorted(R.CASES):
    c = R.CASES[n]
    r = latest.get(n)
    res = '%s (%s): %s' % (r[3], r[2], r[4]) if r else 'not run yet'
    blocks.append('TC-R%d  %s   [%s]' % (n, c['title'], c['kind']))
    code = c['fn'].__code__
    where = '%s:%d (%s)' % (os.path.relpath(code.co_filename, ROOT).replace('\\', '/'), code.co_firstlineno,
                            code.co_name)
    for lab, txt in (('setup', c['setup']), ('1.31', c['bug']), ('fixed', c['fixed']), ('result', res),
                     ('run', 'python -P tools/harness/regress.py %d' % n), ('code', where),
                     ('log', 'work/harness/regress/%d.txt (the last run: setup, observations, screenshots named)' % n)):
        blocks += textwrap.wrap(txt, 112, initial_indent='  %-7s ' % lab, subsequent_indent=' ' * 10)
blocks.append(B1)
tc = open(TC, encoding='utf-8', newline='').read()        # the file mixes CRLF and LF: keep its bytes as they are
nl = '\r\n' if tc.rstrip(' ').endswith('\r\n') else '\n'
if B0 in tc:
    tc = tc[:tc.index(B0)] + nl.join(blocks) + tc[tc.index(B1) + len(B1):]
else:
    tc = tc.rstrip('\r\n') + nl + nl + nl.join(blocks) + nl

bq = open(BQ, encoding='utf-8').read()
changes = []
for n, r in sorted(latest.items()):
    if r[3] not in ('BUG SHOWN', 'BUG SHOWN static', 'NOT SHOWN', 'LATENT'):
        continue
    src = n if n in R.CASES else next((k for k in R.CASES if n in R.CASES[k]['also']), None)
    if src is None:
        continue
    m = re.search(r'(?m)^%d\.\s.*\n(?: {12}.*\n)*' % n, bq)
    if not m:
        continue
    seg = m.group(0)
    # a static check (an ST case, or a play case's static fallback) reads the code, not the running game: no GAME
    static = R.CASES[src]['kind'] == 'ST' or r[3] == 'BUG SHOWN static'
    if r[3] == 'LATENT':                        # the faulty code cannot run in 1.31: the case says why
        line = 'Latent in 1.31 (%s, tools/harness/regress.py %d): %s' % (r[2][:10], src, r[4])
    elif static:
        line = ('Static check (%s, tools/harness/regress.py %d): %s' % (r[2][:10], src, r[4]) if r[3].startswith('BUG SHOWN')
                else 'Static check FAILED (%s, tools/harness/regress.py %d): %s' % (r[2][:10], src, r[4]))
    else:
        line = ('In game (%s, tools/harness/regress.py %d): %s' % (r[2][:10], src, r[4]) if r[3] == 'BUG SHOWN'
                else 'NOT shown in game (%s, tools/harness/regress.py %d): %s' % (r[2][:10], src, r[4]))
    seg = re.sub(r'(?m)^ {12}(In game|NOT shown in game|Latent in 1.31|Static check(?: FAILED)?) \(.*\n'
                 r'(?: {12}(?!Re-checked|In game|NOT shown|Latent in|Static check).*\n)*', '', seg)
    if r[3] == 'BUG SHOWN' and not static:
        h = re.match(r'(\d+\.) (\S+)(\s*)', seg)
        if h.group(2) != 'GAME':
            width = len(h.group(2)) + len(h.group(3))
            seg = h.group(1) + ' ' + 'GAME'.ljust(width) + seg[h.end():]
    seg += '\n'.join(textwrap.wrap(line, 118, initial_indent=' ' * 12, subsequent_indent=' ' * 12)) + '\n'
    if seg != m.group(0):
        changes.append(n)
        bq = bq[:m.start()] + seg + bq[m.end():]
print('TEST_CASES section: %d cases; BUGS_AND_QUIRKS entries updated: %s' % (len(R.CASES), changes))
if '--write' in sys.argv:
    open(TC, 'w', encoding='utf-8', newline='').write(tc)
    if os.path.exists(R.OUT + 'results.tsv'):               # also kept beside the reports (the run history)
        open(ROOT + 'work/harness/regress/results_history.tsv', 'w', encoding='utf-8', newline='\n').write(
            open(R.OUT + 'results.tsv', encoding='utf-8').read())
    open(BQ, 'w', encoding='utf-8', newline='\n').write(bq)
